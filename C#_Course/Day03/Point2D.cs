namespace Day03
{
    internal class Point2D
    {
        public float X { get; set; }
        public float Y { get; set; }
        public Point2D()
        {
            X = 0;
            Y = 0;
        }

        public Point2D(float _X, float _Y)
        {
            X = _X;
            Y = _Y;
        }
    }
}
